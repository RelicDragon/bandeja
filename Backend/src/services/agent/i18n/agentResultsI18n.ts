export const AGENT_RESULTS_I18N_TRANSLATIONS: Record<string, Dictionary> = { ru, sr, es, cs, ar, zh, id, hi, th, ja };

export function agentResultsT(
  locale: string | null | undefined,
  key: AgentResultsI18nKey,
  vars: Record<string, string | number> = {},
): string {
  const template = AGENT_RESULTS_I18N_TRANSLATIONS[agentLang(locale)]?.[key] ?? AGENT_RESULTS_I18N_EN[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}
