export const AGENT_TOOL_PERMISSION_I18N_TRANSLATIONS: Record<string, Dictionary> = {
  ru,
  sr,
  es,
  cs,
  ar,
  zh,
  id,
  hi,
  th,
  ja,
};

/** Localized name + description of a write tool; falls back to English, then the tool name. */
export function agentToolPermissionText(
  locale: string | null | undefined,
  toolName: string,
): { name: string; description: string } {
  const dictionary = AGENT_TOOL_PERMISSION_I18N_TRANSLATIONS[agentLang(locale)] ?? {};
  const en = AGENT_TOOL_PERMISSION_I18N_EN as Record<string, string>;
  const local = dictionary as Record<string, string | undefined>;
  const nameKey = `${toolName}.name`;
  const descriptionKey = `${toolName}.description`;
  return {
    name: local[nameKey] ?? en[nameKey] ?? toolName,
    description: local[descriptionKey] ?? en[descriptionKey] ?? '',
  };
}

export function hasAgentToolPermissionText(toolName: string): boolean {
  const en = AGENT_TOOL_PERMISSION_I18N_EN as Record<string, string>;
  return Boolean(en[`${toolName}.name`] && en[`${toolName}.description`]);
}
